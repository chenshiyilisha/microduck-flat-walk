"""Compile `policy.h` and check it against `selftest.json`, instead of trusting it.

Why this file exists
--------------------
`export_mcu.py` shipped with a caveat: "policy.h has never been compiled, because there is no C
compiler on this machine". Two of the three verifications it did instead were real (a bit-exact
read-back of 26,376 literals, and a same-accumulation-order forward pass agreeing to 3.8e-06),
but neither one can catch a syntax error, a missing header, a C99 vs C89 difference, or a float
ABI problem. Those are exactly the failures that cost an evening on the bench rather than
five seconds here.

So: generate a C harness from selftest.json, compile it with whatever compiler is available,
run it, and require the agreement the handoff promised. Zig is used when present because a
single 80 MB download gives a working C toolchain on a machine with no MSVC and no mingw; it
is looked up in `bin/zig/`, then `$ZIG`, then `PATH`, and the tool says so instead of silently
skipping.

  python tools/mcu_selftest.py                      # compile out/mcu/policy.h and check it
  python tools/mcu_selftest.py --tol 1e-6            # tighter than the promised 1e-5
  python tools/mcu_selftest.py --cc gcc             # any compiler with a -std=c99 and -lm
"""

import argparse
import json
import os
import pathlib
import shutil
import subprocess
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent

MAIN = r"""/* Generated by tools/mcu_selftest.py -- do not edit. */
#include <math.h>
#include <stdio.h>
#include "policy.h"
#include "selftest_vectors.h"

int main(void) {{
  double worst = 0.0;
  int bad_obs = 0;
  for (int v = 0; v < {n}; ++v) {{
    float act[MD_ACT_DIM];
    double worst_v = 0.0;
    if (!md_obs_ok(vec_obs[v])) ++bad_obs;
    md_policy(vec_obs[v], act);
    for (int i = 0; i < MD_ACT_DIM; ++i) {{
      double d = fabs((double)act[i] - (double)vec_expect[v][i]);
      if (d > worst_v) worst_v = d;
      if (d > worst) worst = d;
    }}
    printf("VEC %-16s %.3e  %s\n", vec_name[v], worst_v, worst_v < {tol} ? "ok" : "MISMATCH");
  }}
  printf("WORST %.3e\n", worst);
  printf("REJECTED %d\n", bad_obs);
  printf("MACS %d\n", MD_MACS);
  return worst < {tol} ? 0 : 1;
}}
"""


def find_cc(explicit):
  if explicit:
    return explicit
  if os.environ.get("ZIG"):
    return os.environ["ZIG"]
  for candidate in sorted(ROOT.glob("bin/zig/*/zig.exe")) + sorted(ROOT.glob("bin/zig/*/zig")):
    return str(candidate)
  for name in ("zig", "gcc", "clang", "cc"):
    found = shutil.which(name)
    if found:
      return found
  return None


def cf(x):
  """A C float literal for x. `%.9g` alone gives `0f` and `-1f`, which are not literals."""
  text = f"{x:.9g}"
  if not any(c in text for c in ".eE"):
    text += ".0"
  return text + "f"


def main():
  ap = argparse.ArgumentParser()
  ap.add_argument("--mcu", type=pathlib.Path, default=ROOT / "out" / "mcu")
  ap.add_argument("--tol", type=float, default=1e-5, help="max |C - python| per action, as promised")
  ap.add_argument("--cc", default=None, help="compiler to use; defaults to zig if vendored")
  args = ap.parse_args()

  header, vectors_path = args.mcu / "policy.h", args.mcu / "selftest.json"
  for path in (header, vectors_path):
    if not path.exists():
      raise SystemExit(f"missing {path}; run tools/export_mcu.py first")
  vectors = json.loads(vectors_path.read_text(encoding="utf-8"))

  # Emit the vectors as C arrays rather than parsing JSON from C: the point of the test is the
  # arithmetic, so the plumbing between it and the data should be as dumb as possible.
  lines = ["/* Generated by tools/mcu_selftest.py -- do not edit. */"]
  lines.append(f"#define SELFTEST_TOL {args.tol:.1e}")
  lines.append(f"static const float vec_obs[{len(vectors)}][MD_OBS_DIM] = {{")
  for v in vectors:
    lines.append("  {" + ",".join(cf(x) for x in v["obs"]) + "},")
  lines.append("};")
  lines.append(f"static const float vec_expect[{len(vectors)}][MD_ACT_DIM] = {{")
  for v in vectors:
    lines.append("  {" + ",".join(cf(x) for x in v["action"]) + "},")
  lines.append("};")
  lines.append("static const char *const vec_name[] = {")
  lines.append("  " + ",".join(f'"{v.get("label", str(i))}"' for i, v in enumerate(vectors)))
  lines.append("};")
  (args.mcu / "selftest_vectors.h").write_text("\n".join(lines) + "\n", encoding="utf-8")

  n = len(vectors)
  main_c = args.mcu / "selftest_main.c"
  main_c.write_text(MAIN.format(n=n, tol=f"{args.tol:.1e}"), encoding="utf-8")

  cc = find_cc(args.cc)
  if not cc:
    raise SystemExit(
      "no C compiler found. The handoff promise in policy.h is untested until one exists:\n"
      "  bin/zig/zig-windows-x86_64-0.13.0/zig.exe   (80 MB, https://ziglang.org/download/)\n"
      "  $ZIG=/path/to/zig  or  --cc gcc"
    )
  is_zig = pathlib.Path(cc).name.lower().startswith("zig")
  exe = args.mcu / ("selftest.exe" if os.name == "nt" else "selftest")
  cmd = [cc, "cc"] if is_zig else [cc]
  cmd += ["-O2", "-std=c99", "-Wall", "-Wextra", "-o", str(exe), str(main_c), "-lm"]
  print(f"cc        {cc}")
  print(f"compile    {' '.join(cmd[1:] if is_zig else cmd)}")
  built = subprocess.run(cmd, cwd=args.mcu, capture_output=True, text=True)
  if built.returncode != 0:
    print(built.stdout, built.stderr)
    raise SystemExit(f"COMPILE FAILED (exit {built.returncode}) -- policy.h is not valid C")

  warnings = [line for line in built.stderr.splitlines() if "warning:" in line]
  print(f"warnings   {len(warnings)}")
  for line in warnings[:10]:
    print(f"           {line.strip()}")

  run = subprocess.run([str(exe)], cwd=args.mcu, capture_output=True, text=True)
  print(run.stdout.rstrip())
  if run.stderr.strip():
    print(run.stderr.rstrip())

  print()
  if run.returncode == 0:
    print(f"PASS  every vector within {args.tol:.0e} of the PyTorch reference")
  else:
    print(f"FAIL  exit {run.returncode}; a real board would answer differently from the host")


if __name__ == "__main__":
  main()
