"""Translate the mjlab viser panel to Chinese. There is no built-in language setting.

Evidence that no setting exists (checked 2026-10-24, viser 1.1.1)
----------------------------------------------------------------
* `viser/_assets/` contains only `hdri/` -- no locale/i18n bundle. The frontend
  strings ship inside the bundled JS, there is no runtime language switch.
* `grep -rli "i18n|locale|translat" viser/*.py` hits only `transforms/`
  (geometric *translation*, not localisation).
* Every label in mjlab's panel is a hardcoded English literal.

So the only route is to rewrite those literals. That is what this does: precise
whole-string swaps anchored on the exact literals, applied to site-packages.

What is translated
------------------
Panel titles, tabs, buttons, speed options and the status readout -- i.e. the
things you look at while watching the robot.

What is NOT translated, and cannot be from here
-----------------------------------------------
* viser's own chrome (camera gizmo hints, the top-right toolbar, the connection
  badge). Those live in the compiled frontend.
* Command sliders (twist / head_pose / body_pose). Those are generated by each
  command term's `create_gui`, i.e. by mjlab_microduck's command classes, a
  different file tree.
* Body / site / joint names shown on the 3D model. Those are the model's own
  identifiers; renaming them would break reward/observation lookups.

Safety
------
* A `.zh.bak` copy is written next to the original on first run.
* Idempotent: if the Chinese marker is already present, nothing is written.
* Any anchor that does not match aborts the whole file with a non-zero exit --
  a partial translation is worse than none, because a silently skipped anchor
  looks like "this label has no Chinese version".

Restore: copy `<file>.zh.bak` back over `<file>`.
"""

from __future__ import annotations

import pathlib
import shutil
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
VIEWER = ROOT / ".venv-mjlab/Lib/site-packages/mjlab/viewer/viser/viewer.py"

MARKER = "状态："

# (anchor, replacement) -- each anchor must appear exactly once.
SWAPS: list[tuple[str, str]] = [
    # Tabs
    ('add_tab("Controls", icon=', 'add_tab("控制", icon='),
    ('add_tab("Visualization", icon=', 'add_tab("可视化", icon='),
    ('add_tab("Groups", icon=', 'add_tab("分组", icon='),
    ('add_tab("Checkpoints"', 'add_tab("检查点"'),
    # Folders
    ('add_folder("Info")', 'add_folder("状态")'),
    ('add_folder("Simulation")', 'add_folder("仿真")'),
    ('add_folder("Commands")', 'add_folder("指令")'),
    ('add_folder("Scene")', 'add_folder("场景")'),
    ('add_folder("Camera Feeds")', 'add_folder("相机画面")'),
    # Buttons
    ('"Play" if self._is_paused else "Pause"', '"播放" if self._is_paused else "暂停"'),
    ('"Step",', '"单步",'),
    ('"Reset Environment"', '"重置环境"'),
    # Speed group: the option strings are compared against later, so both the
    # declaration and the handler must change together or the buttons go dead.
    (
        'options=["Slower", "1x", "Faster"],',
        'options=["更慢", "1x", "更快"],',
    ),
    ('if event.target.value == "Slower":', 'if event.target.value == "更慢":'),
    # Status readout
    ('<strong>Status:</strong>', '<strong>状态：</strong>'),
    ('{"Paused" if status.paused else "Running"}', '{"已暂停" if status.paused else "运行中"}'),
    ('<strong>Steps:</strong>', '<strong>步数：</strong>'),
    ('<strong>Speed:</strong>', '<strong>速度：</strong>'),
    ('<strong>Target RT:</strong>', '<strong>目标实时：</strong>'),
    ('<strong>Actual RT:</strong>', '<strong>实际实时：</strong>'),
    ('[CAPPED]', '[受限]'),
    ('<strong>Error:</strong>', '<strong>错误：</strong>'),
]


def main() -> int:
    if not VIEWER.exists():
        print(f"missing {VIEWER}", file=sys.stderr)
        return 1

    text = VIEWER.read_text(encoding="utf-8")
    if MARKER in text:
        print(f"  = already translated ({MARKER!r} present), nothing to do")
        return 0

    # Some labels legitimately appear twice (the play/pause button is set once at
    # construction and again on every toggle; the status line exists in both the
    # controls tab and the checkpoint tab), so we only require >=1 occurrence and
    # replace every instance.
    missing = [a for a, _ in SWAPS if text.count(a) == 0]
    if missing:
        print("  !! anchors not found (expected at least 1 each):", file=sys.stderr)
        for a in missing:
            print(f"      {a!r}", file=sys.stderr)
        print("  aborting: file left untouched", file=sys.stderr)
        return 1

    bak = VIEWER.with_suffix(".py.zh.bak")
    if not bak.exists():
        shutil.copy2(VIEWER, bak)
        print(f"  backup -> {bak.name}")

    for a, b in SWAPS:
        text = text.replace(a, b)
    VIEWER.write_text(text, encoding="utf-8")
    print(f"  + translated {len(SWAPS)} labels in {VIEWER.name}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
